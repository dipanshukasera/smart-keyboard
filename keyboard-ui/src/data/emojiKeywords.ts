const KEYWORDS = Object.keys(EMOJI_KEYWORDS);

/**
 * The emoji for what's been typed so far, or null. An exact keyword match
 * wins ("love" -> ❤️); otherwise, from 3 letters on, the shortest keyword
 * starting with it ("happ" -> 😊 via "happy"), so the chip shows up while
 * the word is still being typed rather than only once it's complete.
 */
export function getEmojiSuggestion(word: string): string | null {
  const typed = word.toLowerCase();
  if (!typed) return null;
  if (EMOJI_KEYWORDS[typed]) return EMOJI_KEYWORDS[typed];
  if (typed.length < 3) return null;
  let best: string | null = null;
  for (const key of KEYWORDS) {
    if (key.startsWith(typed) && (best === null || key.length < best.length)) {
      best = key;
    }
  }
  return best ? EMOJI_KEYWORDS[best] : null;
}
